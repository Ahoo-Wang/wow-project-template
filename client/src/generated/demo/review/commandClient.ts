import type { PartialBy } from "@ahoo-wang/fetcher";
import { ContentTypeValues } from "@ahoo-wang/fetcher";
import { type ApiMetadata, type ApiMetadataCapable, api, attribute, autoGeneratedError, del, path, put, request } from "@ahoo-wang/fetcher-decorator";
import { JsonEventStreamResultExtractor } from "@ahoo-wang/fetcher-eventstream";
import type { ApplyResourceTagsCommand, CommandBody, CommandRequest, CommandResult, CommandResultEventStream, DeleteAggregateCommand, RecoverAggregateCommand } from "@ahoo-wang/fetcher-wow";
import type { ApproveReview, RejectReview } from "./types";
import { DEMO_BOUNDED_CONTEXT_ALIAS } from "../boundedContext";

export enum ReviewCommandEndpointPaths {
    APPROVE_REVIEW = '/tenant/{tenantId}/review/{id}/approve',
    DEFAULT_APPLY_RESOURCE_TAGS = '/tenant/{tenantId}/review/{id}/tags',
    DEFAULT_DELETE_AGGREGATE = '/tenant/{tenantId}/review/{id}',
    DEFAULT_RECOVER_AGGREGATE = '/tenant/{tenantId}/review/{id}/recover',
    REJECT_REVIEW = '/tenant/{tenantId}/review/{id}/reject'
}

export type ApproveReviewCommand = CommandBody<PartialBy<ApproveReview, 'comment'>>;
export type RejectReviewCommand = CommandBody<RejectReview>;

const DEFAULT_COMMAND_CLIENT_OPTIONS: ApiMetadata = {
    basePath: DEMO_BOUNDED_CONTEXT_ALIAS
};

@api()
export class ReviewCommandClient<R = CommandResult> implements ApiMetadataCapable {
    constructor(public readonly apiMetadata: ApiMetadata = DEFAULT_COMMAND_CLIENT_OPTIONS) {
    }

    /**
     * 审核通过
     * - operationId: `demo.review.approve_review`
     * - path: `/tenant/{tenantId}/review/{id}/approve`
     */
    @put(ReviewCommandEndpointPaths.APPROVE_REVIEW)
    approveReview(@path('id') id: string, @request() commandRequest: CommandRequest<ApproveReviewCommand>, @attribute() attributes?: Record<string, any>): Promise<R> {
        throw autoGeneratedError(id, commandRequest, attributes);
    }

    /**
     * Apply ABAC Resource Tags
     * - operationId: `demo.review.default_apply_resource_tags`
     * - path: `/tenant/{tenantId}/review/{id}/tags`
     */
    @put(ReviewCommandEndpointPaths.DEFAULT_APPLY_RESOURCE_TAGS)
    defaultApplyResourceTags(@path('id') id: string, @request() commandRequest: CommandRequest<ApplyResourceTagsCommand>, @attribute() attributes?: Record<string, any>): Promise<R> {
        throw autoGeneratedError(id, commandRequest, attributes);
    }

    /**
     * Delete aggregate
     * - operationId: `demo.review.default_delete_aggregate`
     * - path: `/tenant/{tenantId}/review/{id}`
     */
    @del(ReviewCommandEndpointPaths.DEFAULT_DELETE_AGGREGATE)
    defaultDeleteAggregate(@path('id') id: string, @request() commandRequest?: CommandRequest<DeleteAggregateCommand>, @attribute() attributes?: Record<string, any>): Promise<R> {
        throw autoGeneratedError(id, commandRequest, attributes);
    }

    /**
     * Recover deleted aggregate
     * - operationId: `demo.review.default_recover_aggregate`
     * - path: `/tenant/{tenantId}/review/{id}/recover`
     */
    @put(ReviewCommandEndpointPaths.DEFAULT_RECOVER_AGGREGATE)
    defaultRecoverAggregate(@path('id') id: string, @request() commandRequest?: CommandRequest<RecoverAggregateCommand>, @attribute() attributes?: Record<string, any>): Promise<R> {
        throw autoGeneratedError(id, commandRequest, attributes);
    }

    /**
     * 审核驳回
     * - operationId: `demo.review.reject_review`
     * - path: `/tenant/{tenantId}/review/{id}/reject`
     */
    @put(ReviewCommandEndpointPaths.REJECT_REVIEW)
    rejectReview(@path('id') id: string, @request() commandRequest: CommandRequest<RejectReviewCommand>, @attribute() attributes?: Record<string, any>): Promise<R> {
        throw autoGeneratedError(id, commandRequest, attributes);
    }
}

@api('', {
    headers: { Accept: ContentTypeValues.TEXT_EVENT_STREAM },
    resultExtractor: JsonEventStreamResultExtractor,
})
export class ReviewStreamCommandClient extends ReviewCommandClient<CommandResultEventStream> {
    constructor(apiMetadata: ApiMetadata = DEFAULT_COMMAND_CLIENT_OPTIONS) {
        super(apiMetadata);
    }
}
